"""Import an exported ZEFM MySQL `dictionaries` JSONL file, one UTF-8 file per language.

Usage: python3 -m zefm.storage.import_legacy_dictionaries export.jsonl
       python3 -m zefm.storage.import_legacy_dictionaries export.jsonl --dry-run
The source JSONL is generated by export_legacy_tables.py from a separately
restored MyISAM database. This does not read .MYD files directly.
"""
import argparse
import sys
from .lexicons import import_lexicons,default_lexicon_dir


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('export',help='UTF-8 JSONL from the original dictionaries SQL table')
    p.add_argument('--output-dir',default=str(default_lexicon_dir()))
    p.add_argument('--force',action='store_true',help='Replace existing per-language files')
    p.add_argument('--dry-run',action='store_true',help='Check and count entries without writing')
    a=p.parse_args(argv)
    try:
        counts=import_lexicons(a.export,a.output_dir,overwrite=a.force,dry_run=a.dry_run)
    except (OSError,UnicodeError,ValueError) as exc:
        print(f'Dictionary import failed: {exc}',file=sys.stderr)
        return 1
    for code,count in sorted(counts.items()):print(f'{code}: {count} records')
    if not counts:print('No dictionary entries found')
    elif a.dry_run:print('Dry run: no files changed')
    else:print(f'Imported to {a.output_dir}')
    return 0


if __name__=='__main__':raise SystemExit(main())
